# The participation id of the rows of one answer is random on each side: it is derived from the user and the consultation by
# a trigger, so that the DB diff compares it (the runner binds ONE generated UUID per row pair, not a UUID shared by several
# rows). The trigger only changes non-zero participation ids.
TRIGGER_SQL = [
    "CREATE OR REPLACE FUNCTION s6_participation() RETURNS trigger AS $$ BEGIN IF NEW.participation_id IS NOT NULL AND NEW.participation_id <> '00000000-0000-0000-0000-000000000000' THEN NEW.participation_id := md5(coalesce(NEW.user_id::text, '') || '/' || coalesce(NEW.consultation_id, ''))::uuid; END IF; RETURN NEW; END $$ LANGUAGE plpgsql",
    "DROP TRIGGER IF EXISTS s6_participation ON reponses_consultation",
    "CREATE TRIGGER s6_participation BEFORE INSERT ON reponses_consultation FOR EACH ROW EXECUTE FUNCTION s6_participation()",
]


def setup(sql=(), **kw):
    s = {"sql": list(TRIGGER_SQL) + list(sql)}
    s.update(kw)
    return s


_xff = [0]


def xff(n=None):
    """A distinct client IP (a distinct rate limit counter)."""
    if n is None:
        _xff[0] += 1
        n = _xff[0]
    return {"X-Forwarded-For": "10.6.%d.%d" % (n // 250, n % 250 + 1)}


def r_(q, choices=(), text=None):
    """A ReponseConsultationJson."""
    return {"questionId": q, "choiceIds": list(choices), "responseText": text}


def body(responses, consultation_id="x"):
    return {"consultationId": consultation_id, "responses": responses}


def post(id, cid, responses, user=None, headers=None, after="", **kw):
    """POST /consultations/{cid}/responses (after: text appended to the path, e.g. a query string)"""
    s = {"method": "POST", "body": body(responses, cid)}
    if user:
        s["as"] = user
    h = dict(xff())
    if headers:
        h.update(headers)
    s["headers"] = h
    s.update(kw)
    return step(id, "/consultations/%s/responses%s" % (cid, after), **s)


def post_raw(id, cid, raw, user=None, content_type="application/json", headers=None, **kw):
    s = {"method": "POST", "bodyRaw": raw}
    if content_type:
        s["contentType"] = content_type
    if user:
        s["as"] = user
    h = dict(xff())
    if headers:
        h.update(headers)
    s["headers"] = h
    s.update(kw)
    return step(id, "/consultations/%s/responses" % cid, **s)


