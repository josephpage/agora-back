def many_finished(count, base=5000):
    out = []
    territories = ["France", "Nord", "Bretagne", "Ile-de-France", "France", "France"]
    for k in range(count):
        n = base + k
        update = now("-%dd" % (3 + k % 40)) if k % 3 != 2 else None
        label = ["Dernière ligne droite", "Merci !", None, "Réponse publiée"][k % 4] if update else None
        th = UNKNOWN_THEMATIQUE if k % 17 == 16 else copy.deepcopy(THEMES[k % 6])
        out.append(fin(n, now("-%dd" % (10 + k % 90)), territories[k % 6], th, update, label))
    return out


