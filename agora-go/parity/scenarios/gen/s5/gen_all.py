def fin(n, end, territoire="France", thematique=None, update=None, label=None, **kw):
    """A finished consultation of the variants (documentId vc<n>); update: date of its latest other content."""
    cid = "vc%04d" % n
    autres = [variants.autre(cid, 1, update, [], flamme_label=label)] if update else []
    c = variants.consultation(n, start=now("-200d"), end=end, secs_avant=[], secs_apres=[], autres=autres, qs=False, territoire=territoire, **kw)
    if thematique:
        c["thematique"] = thematique
    return c


