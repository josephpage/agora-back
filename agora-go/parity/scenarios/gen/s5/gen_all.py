def answered_sql(rows):
    """rows: [(consultation_id, user_id)]; a repeated pair is a duplicate row (the queries use DISTINCT)."""
    vals = ["('dddddddd-0000-4000-a000-%012d', '%s', now(), '%s')" % (i + 1, c, u) for i, (c, u) in enumerate(rows)]
    out = []
    for i in range(0, len(vals), 200):
        out.append("INSERT INTO user_answered_consultation (id, consultation_id, participation_date, user_id) VALUES " + ", ".join(vals[i:i + 200]))
    # the order of a SELECT DISTINCT without ORDER BY feeds the Strapi URI: same statistics on both databases
    out.append("ANALYZE user_answered_consultation")
    return out


