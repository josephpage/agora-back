def roles_matrix(prefix, path, ok_as=ADMIN, method="GET"):
    """Anonymous, bad token, regular user, banned, publisher, moderator, and the admin who may call the route."""
    return [
        step(prefix + "-anon", path, method=method),
        step(prefix + "-bad-jwt", path, method=method, bearer="abc.def.ghi"),
        step(prefix + "-user", path, method=method, **{"as": R[1]}),
        step(prefix + "-banned", path, method=method, **{"as": BANNED}),
        step(prefix + "-publisher", path, method=method, **{"as": PUBLISHER}),
        step(prefix + "-moderator", path, method=method, **{"as": MODERATOR}),
        step(prefix + "-admin", path, method=method, **{"as": ok_as}),
    ]


def paginated_steps(prefix, user, pages, query=""):
    return [step("%s-p%s" % (prefix, p), "/notifications/paginated/%s%s" % (p, query), **{"as": user}) for p in pages]


