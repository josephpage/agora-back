def step(id, path, **kw):
    s = {"id": id}
    s.update(kw)
    s["path"] = path
    order = ["id", "method", "path"]
    out = {k: s[k] for k in order if k in s}
    out.update({k: v for k, v in s.items() if k not in out})
    return out


def scenario(name, steps, tags=("S4",), dbdiff="none", setup=None, skip=None):
    d = {"name": name, "tags": list(tags), "dbdiff": dbdiff}
    if skip:
        d["skip"] = skip
    if setup:
        d["setup"] = setup
    d["steps"] = steps
    return d


def jd(v):
    """JSON text that is also valid YAML: non printable / special characters stay escaped."""
    t = json.dumps(v, ensure_ascii=False)
    out = []
    for ch in t:
        o = ord(ch)
        if o in (0x7F, 0x2028, 0x2029, 0xFEFF, 0xFFFE, 0xFFFF) or 0x80 <= o <= 0x9F or 0xD800 <= o <= 0xDFFF:
            out.append("\\u%04x" % o)
        else:
            out.append(ch)
    return "".join(out)


def dump(scenarios, path, comment=None):
    parts = []
    for s in scenarios:
        lines = []
        lines.append("name: " + json.dumps(s["name"]))
        lines.append("tags: " + json.dumps(s["tags"]))
        lines.append("dbdiff: " + json.dumps(s["dbdiff"]))
        if "skip" in s:
            lines.append("skip: " + json.dumps(s["skip"]))
        if "setup" in s:
            lines.append("setup: " + jd(s["setup"]))
        lines.append("steps:")
        for st in s["steps"]:
            lines.append("  - " + jd(st))
        parts.append("\n".join(lines))
    with open(path, "w") as f:
        f.write(HEADER)
        if comment:
            for l in comment.strip().splitlines():
                f.write("# " + l + "\n")
        f.write("\n---\n".join(parts) + "\n")


def faults(model, mode, delay=None):
    f = {"model": model, "mode": mode}
    if delay:
        f["delayMs"] = delay
    return {"strapiFaults": [f]}


def override_fixture(model, fixture):
    return {"strapiOverrides": [{"model": model, "fixture": fixture}]}


def override_data(model, data):
    return {"strapiOverrides": [{"model": model, "data": data}]}


