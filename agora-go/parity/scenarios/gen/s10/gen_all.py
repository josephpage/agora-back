def body_variants(key, valid_id):
    """(name, body or None, extra step args) for a request list under `key`."""
    return [
        ("valid", {key: [valid_id]}, {}),
        ("empty-list", {key: []}, {}),
        ("unknown-ids", {key: [UNKNOWN]}, {}),
        ("malformed-ids", {key: ["not-a-uuid", "", "00000000-0000-4000-9000-00000000000"]}, {}),
        ("missing-field", {}, {}),
        ("null-list", {key: None}, {}),
        ("string-instead-of-list", {key: "x"}, {}),
        ("object-instead-of-list", {key: {"a": 1}}, {}),
        ("number-instead-of-list", {key: 5}, {}),
        ("null-element", {key: [None]}, {}),
        ("null-element-after-valid", {key: [valid_id, None]}, {}),
        ("mixed", {key: [valid_id, UNKNOWN, "not-a-uuid", R3_UPPER, R3_SHORT]}, {}),
        ("duplicates", {key: [valid_id, valid_id]}, {}),
        ("number-element", {key: [1]}, {}),
        ("boolean-element", {key: [True]}, {}),
        ("object-element", {key: [{"id": valid_id}]}, {}),
        ("nested-list-element", {key: [[valid_id]]}, {}),
        ("wrong-key-name", {"userIDs": [valid_id]}, {}),
        ("extra-property", {key: [valid_id], "other": 1}, {}),
        ("array-body", [valid_id], {}),
        ("string-body", "x", {}),
        ("null-body-json", None, {"bodyRaw": "null", "contentType": "application/json"}),
        ("invalid-json", None, {"bodyRaw": "{", "contentType": "application/json"}),
        ("empty-body-no-type", None, {}),
    ]


def body_scenarios():
    specs = [
        ("delete", "DELETE", "/admin/delete_users", "userIDsToDelete", R[6]),
        ("upgrade", "POST", "/admin/upgrade_users_to_publisher", "usersID", R[3]),
        ("downgrade", "POST", "/admin/downgrade_users", "usersID", R[5]),
    ]
    out = []
    for route, method, path, key, valid_id in specs:
        for name, body, extra in body_variants(key, valid_id):
            args = {"method": method}
            if extra.get("bodyRaw") is not None:
                args["bodyRaw"] = extra["bodyRaw"]
                if "contentType" in extra:
                    args["contentType"] = extra["contentType"]
            elif body is not None:
                args["body"] = body
            s = step("%s-%s" % (route, name), path, **dict(args, **{"as": ADMIN}))
            steps = [s]
            if name in ("valid", "mixed", "duplicates") and route != "delete":
                # the rights of the changed user, read for the first time after the change
                steps.append(step("%s-%s-rights" % (route, name), "/consultations", **{"as": R[3] if route == "upgrade" else R[5]}))
            if name == "valid" and route == "delete":
                steps.append(step("delete-valid-profile-after", "/profile", **{"as": R[6]}))
            out.append(scenario("S10-body-%s-%s" % (route, name), steps, tags=TAG, dbdiff="step"))
    return out


