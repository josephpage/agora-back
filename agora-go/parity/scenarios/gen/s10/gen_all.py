def role_steps(prefix, path, method, body=None, admin=True):
    """The same request for every role of the matrix (anonymous, bad token, user, banned, publisher, moderator, admin).
    admin=False leaves the admin out when the request would run a task (the weekly tasks)."""
    kw = {} if body is None else {"body": body}
    out = [
        step(prefix + "-anon", path, method=method, **kw),
        step(prefix + "-bad-jwt", path, method=method, bearer="abc.def.ghi", **kw),
        step(prefix + "-user", path, method=method, **dict(kw, **{"as": R[1]})),
        step(prefix + "-banned", path, method=method, **dict(kw, **{"as": BANNED})),
        step(prefix + "-publisher", path, method=method, **dict(kw, **{"as": PUBLISHER})),
        step(prefix + "-moderator", path, method=method, **dict(kw, **{"as": MODERATOR})),
    ]
    if admin:
        out.append(step(prefix + "-admin", path, method=method, **dict(kw, **{"as": ADMIN})))
    return out


