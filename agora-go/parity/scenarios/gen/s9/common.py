HEADER = "# Generated by parity/scenarios/gen/s9 (see parity/ledger/S9.md); edit the generator, not this file.\n"


def step(id, path, **kw):
    s = {"id": id}
    if "method" in kw and kw["method"] == "GET":
        del kw["method"]
    s.update(kw)
    s["path"] = path
    # stable key order: id, method, path, ...
    order = ["id", "method", "path"]
    out = {k: s[k] for k in order if k in s}
    out.update({k: v for k, v in s.items() if k not in out})
    return out


def scenario(name, steps, tags=("S9",), dbdiff="none", setup=None, skip=None):
    d = {"name": name, "tags": list(tags), "dbdiff": dbdiff}
    if setup:
        d["setup"] = setup
    d["steps"] = steps
    return d


def jd(v):
    """JSON text that is also valid YAML: non printable / special characters stay escaped."""
    t = json.dumps(v, ensure_ascii=False)
    out = []
    for ch in t:
        o = ord(ch)
        if o in (0x7F, 0x2028, 0x2029, 0xFEFF, 0xFFFE, 0xFFFF) or 0x80 <= o <= 0x9F or 0xD800 <= o <= 0xDFFF:
            out.append("\\u%04x" % o)
        else:
            out.append(ch)
    return "".join(out)


def dump(scenarios, path, comment=None):
    parts = []
    for s in scenarios:
        lines = []
        lines.append("name: " + json.dumps(s["name"]))
        lines.append("tags: " + json.dumps(s["tags"]))
        lines.append("dbdiff: " + json.dumps(s["dbdiff"]))
        if "setup" in s:
            lines.append("setup: " + jd(s["setup"]))
        lines.append("steps:")
        for st in s["steps"]:
            lines.append("  - " + jd(st))
        parts.append("\n".join(lines))
    with open(path, "w") as f:
        f.write(HEADER)
        if comment:
            for l in comment.strip().splitlines():
                f.write("# " + l + "\n")
        f.write("\n---\n".join(parts) + "\n")


def http_matrix(path, sep="?"):
    """Spring MVC matrix for a public GET route (no body)."""
    q = lambda extra: path + sep + extra
    return [
        step("anon", path),
        step("anon-again", path, repeat=2),
        step("user", path, **{"as": U1}),
        step("banned", path, **{"as": BANNED}),
        step("admin", path, **{"as": ADMIN}),
        step("unknown-user-jwt", path, **{"as": "00000000-0000-4000-9000-0000000000ff"}),
        step("bad-jwt", path, bearer="abc.def.ghi"),
        step("xml", q("mediaType=xml")),
        step("xml-user", q("mediaType=xml"), **{"as": U1}),
        step("xml-upper", q("mediaType=XML")),
        step("json-explicit", q("mediaType=json")),
        step("foo", q("mediaType=foo")),
        step("foo-user", q("mediaType=foo"), **{"as": U1}),
        step("empty-media", q("mediaType=")),
        step("other-params", q("x=1&y=%C3%A9")),
        step("accept-xml-header", path, headers={"Accept": "application/xml"}),
        step("accept-text", path, headers={"Accept": "text/plain"}),
        step("head", path, method="HEAD"),
        step("head-xml", q("mediaType=xml"), method="HEAD"),
        step("head-foo", q("mediaType=foo"), method="HEAD"),
        step("post", path, method="POST"),
        step("put", path, method="PUT"),
        step("delete", path, method="DELETE"),
        step("options", path, method="OPTIONS"),
        step("cors-get", path, headers={"Origin": "https://www.agora.gouv.fr"}),
        step("cors-preflight", path, method="OPTIONS",
             headers={"Origin": "https://www.agora.gouv.fr", "Access-Control-Request-Method": "GET"}),
        step("trailing-slash", path + "/"),
        step("sub-path", path + "/x"),
    ]


def fault_steps(path, with_xml=True):
    s = [step("json", path), step("json-again", path), step("user", path, **{"as": U1})]
    if with_xml:
        s.append(step("xml", path + "?mediaType=xml"))
    s.append(step("foo", path + "?mediaType=foo"))
    return s


def faults(model, mode, delay=None):
    f = {"model": model, "mode": mode}
    if delay:
        f["delayMs"] = delay
    return {"strapiFaults": [f]}


def override(model, data):
    return {"strapiOverrides": [{"model": model, "data": data}]}


# rich text helpers
def text(t, **marks):
    d = {"type": "text", "text": t}
    d.update(marks)
    return d


def para(*children):
    return {"type": "paragraph", "children": list(children) or [text("")]}
