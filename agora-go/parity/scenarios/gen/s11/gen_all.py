class Dump(yaml.SafeDumper):
    pass


def _str(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


Dump.add_representer(str, _str)
Dump.ignore_aliases = lambda self, data: True


def dump(scenarios, path):
    with open(path, "w") as f:
        f.write(HEADER)
        f.write(yaml.dump_all(scenarios, Dumper=Dump, sort_keys=False, width=1000, default_flow_style=None, allow_unicode=True))


def step(id, path, **kw):
    s = {"id": id}
    s.update(kw)
    s["path"] = path
    order = ["id", "method", "path"]
    out = {k: s[k] for k in order if k in s}
    out.update({k: v for k, v in s.items() if k not in out})
    return out


def sc(name, steps, setup_sql=None, dbdiff="step", tags=("S11",), skip=None):
    d = {"name": name, "tags": list(tags), "dbdiff": dbdiff}
    if skip:
        d["skip"] = skip
    if setup_sql:
        d["setup"] = {"sql": list(setup_sql)}
    d["steps"] = steps
    return d


def q(s):
    return s.replace("'", "''")


def cert_sql(status, expires, created, key=KEY1, pem=CERT_A, deployed="NULL", domain=DOMAIN, id=None):
    idc, idv = ("id, ", "'%s'::uuid, " % id) if id else ("", "")
    return ("INSERT INTO acme_certificate (%sdomain, certificate, private_key, expires_at, created_at, status, deployed_at) "
            "VALUES (%s'%s', '%s', '%s', %s, %s, '%s', %s)") % (idc, idv, domain, q(pem), key, expires, created, status, deployed)


def order_sql(status, created, key=KEY3, url="http://localhost:9/stub/acme/order/unreachable", domain=DOMAIN):
    return ("INSERT INTO acme_order (domain, order_url, domain_key_pem, status, created_at) VALUES ('%s', '%s', '%s', '%s', %s)"
            % (domain, url, key, status, created))


def account_sql(created, key=KEY2, url="NULL", server="http://localhost:9/directory"):
    u = "'%s'" % url if url != "NULL" else "NULL"
    return ("INSERT INTO acme_account (server_url, account_url, key_pem, created_at) VALUES ('%s', %s, '%s', %s)"
            % (server, u, key, created))


def HOUR(n):
    return "date_trunc('hour', now()) - interval '%s hours'" % n


def future(days):
    return "%s + interval '%d days'" % (DAY, days)


def past(days):
    return "%s - interval '%d days'" % (DAY, days)


