def renew():
    R = "/admin/acme/renew-certificate"
    out = []
    reset = admin("reset-stub", "/admin/stub/acme/calls/reset", method="DELETE")
    calls = lambda id: admin(id, "/admin/stub/acme/calls", compare=CALLS_IGNORE)
    calls_ids = lambda id: admin(id, "/admin/stub/acme/calls", compare=CALLS_IGNORE_IDS)
    calls_none = lambda id: admin(id, "/admin/stub/acme/calls", compare={"body": "status"})
    last = lambda id: admin(id, "/admin/stub/acme/last-deploy", compare=LAST_DEPLOY_IGNORE)
    last_rand = lambda id: admin(id, "/admin/stub/acme/last-deploy", compare={"ignore": ["$.lastDeployedAt", "$.lastDeployedCertPreview"]})

    out.append(sc("S11-renew-deployed-valid", [
        reset, admin("renew", R, method="POST"), calls("calls-empty"), last("last-deploy-empty"),
    ], [cert_sql("DEPLOYED", future(60), past(2), deployed=past(1))]))

    out.append(sc("S11-renew-deployed-31-days", [reset, admin("renew", R, method="POST"), calls("calls-empty")],
                  [cert_sql("DEPLOYED", future(31), past(2), deployed=past(1))]))

    out.append(sc("S11-renew-to-deploy-valid", [reset, 
        admin("renew", R, method="POST"), calls("calls"), last("last-deploy"),
        admin("renew-again", R, method="POST"), calls("calls-after-second"),
    ], [cert_sql("TO_DEPLOY", future(60), past(2)), order_sql("ORDER_FINALIZING", past(1))]))

    out.append(sc("S11-renew-to-deploy-31-days", [admin("renew", R, method="POST"), last("last-deploy")],
                  [cert_sql("TO_DEPLOY", future(31), past(2), pem=CERT_B)]))

    out.append(sc("S11-renew-latest-certificate-wins", [reset, admin("renew", R, method="POST"), last("last-deploy"), admin("renew-2", R, method="POST"), calls("calls")],
                  [cert_sql("DEPLOYED", future(300), past(5), deployed=past(5), pem=CERT_A),
                   cert_sql("TO_DEPLOY", future(100), past(1), pem=CERT_B)]))

    out.append(sc("S11-renew-latest-deployed-older-to-deploy", [reset, admin("renew", R, method="POST"), calls("calls-empty")],
                  [cert_sql("TO_DEPLOY", future(300), past(5), pem=CERT_A),
                   cert_sql("DEPLOYED", future(100), past(1), deployed=past(1), pem=CERT_B)]))

    out.append(sc("S11-renew-other-domain-ignored", [reset, admin("renew", R, method="POST"), calls_none("calls")],
                  [cert_sql("DEPLOYED", future(300), past(1), deployed=past(1), domain="other.example")], dbdiff="none"))

    out.append(sc("S11-renew-to-deploy-corrupted-key", [reset, admin("renew", R, method="POST"), calls("calls-empty")],
                  [cert_sql("TO_DEPLOY", future(60), past(2), key="AAAA" + KEY1[4:])]))

    out.append(sc("S11-renew-to-deploy-not-base64-key", [reset, admin("renew", R, method="POST"), calls("calls-empty")],
                  [cert_sql("TO_DEPLOY", future(60), past(2), key="***not base64***")]))

    out.append(sc("S11-renew-unknown-status", [reset, admin("renew", R, method="POST"), calls("calls-empty")],
                  [cert_sql("FOO", future(60), past(2))]))

    out.append(sc("S11-renew-lowercase-status", [admin("renew", R, method="POST")],
                  [cert_sql("deployed", future(60), past(2))]))

    # expiring / missing certificate: a new order through the stub (random keys → structure checked by S11_db_structure)
    # the number of GET /directory differs by design (S11-N1): the call lists are compared by tests/parity_it_test.go
    prov = lambda name, sql, **kw: sc(name, [reset, admin("renew", R, method="POST"), calls_none("calls"), last_rand("last-deploy"),
                                              admin("renew-again", R, method="POST"), calls_none("calls-second")], sql, dbdiff="none", **kw)
    out.append(prov("S11-renew-first-issuance", None))
    out.append(prov("S11-renew-expiring-deployed", [cert_sql("DEPLOYED", future(29), past(60), deployed=past(60))]))
    out.append(prov("S11-renew-expiring-to-deploy", [cert_sql("TO_DEPLOY", future(10), past(60))]))
    out.append(prov("S11-renew-expired", [cert_sql("DEPLOYED", past(3), past(90), deployed=past(90))]))
    out.append(prov("S11-renew-stale-order-and-account", [account_sql(past(100)), order_sql("CHALLENGE_PENDING", HOUR("169"))]))
    out.append(prov("S11-renew-stale-order-finalizing", [order_sql("ORDER_FINALIZING", HOUR("200"))]))

    # an incident order younger than 168 h is resumed; without a usable account/order the run fails and nothing changes
    out.append(sc("S11-renew-pending-order-no-account", [reset, admin("renew", R, method="POST"), calls("calls-empty")],
                  [order_sql("CHALLENGE_PENDING", HOUR("1"))]))
    out.append(sc("S11-renew-pending-order-167h-no-account", [admin("renew", R, method="POST")],
                  [order_sql("ORDER_FINALIZING", HOUR("167"))]))
    out.append(sc("S11-renew-pending-order-account-without-url", [admin("renew", R, method="POST")],
                  [order_sql("CHALLENGE_PENDING", HOUR("1")), account_sql(past(1), server="http://STUB/directory")],
                  skip="the account server_url must be the stub URL of each side: covered by the Go integration test"))
    out.append(sc("S11-renew-pending-order-unreachable", [admin("renew", R, method="POST"), calls("calls")],
                  [order_sql("CHALLENGE_PENDING", HOUR("1")), account_sql(past(1), url="http://localhost:9/account/1", server="http://STUB/directory")],
                  skip="see S11-renew-pending-order-account-without-url"))
    out.append(sc("S11-renew-pending-order-corrupted-domain-key", [admin("renew", R, method="POST")],
                  [order_sql("CHALLENGE_PENDING", HOUR("1"), key="***")]))
    out.append(sc("S11-renew-order-unknown-status", [admin("renew", R, method="POST")],
                  [order_sql("WHATEVER", HOUR("1"))]))
    return out


