def sql_insert_open(first, count, prefix="8100", thematique="th0000000000000000000001", user="00000000-0000-4000-9000-000000000004",
                    status=0, title="Many", base="2026-09-01 12:00:00"):
    """INSERT `count` QaGs of ids 00000000-0000-4000-<prefix>-<n> with distinct post dates (no ORDER BY ties)."""
    return (
        "INSERT INTO qags (id, title, description, post_date, status, thematique_id, user_id, username) "
        "SELECT ('00000000-0000-4000-%s-' || lpad(to_hex(i), 12, '0'))::uuid, '%s ' || i, 'Description ' || i, "
        "timestamp '%s' + (i || ' minutes')::interval, %d, '%s', '%s'::uuid, 'Many' || i "
        "FROM generate_series(%d, %d) AS i" % (prefix, title, base, status, thematique, user, first, first + count - 1)
    )


def gen_ids_sql(prefix="8100", first=1, count=1):
    """The ids produced by sql_insert_open (for lock / moderation steps): literal strings."""
    return ["00000000-0000-4000-%s-%012x" % (prefix, i) for i in range(first, first + count)]
