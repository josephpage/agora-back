def mint_path(path, params):
    """Raw path with the query string built by hand (repeated keys, raw bytes)."""
    return path + "?" + "&".join("%s=%s" % (k, quote(v, safe="")) for k, v in params)


def st(id, path=None, method=None, query=None, as_=None, headers=None, sleep=None, compare=None,
       body=None, bearer=None, capture=None):
    """One step. `query` is a dict (URL-encoded by the runner), `path` a plain path."""
    d = {"id": id}
    if method:
        d["method"] = method
    d["path"] = path
    if query is not None:
        d["query"] = query
    if as_ is not None:
        d["as"] = as_
    if headers:
        d["headers"] = headers
    if bearer is not None:
        d["bearer"] = bearer
    if body is not None:
        d["body"] = body
    if sleep:
        d["sleepMs"] = sleep
    if compare:
        d["compare"] = compare
    if capture:
        d["capture"] = capture
    return d


